#include <bitset>
#include <iostream>

union mifuncion {
  int i;
  float f;
};

int main() {
  union mifuncion mf;
  mf.i = 0x4209999a; // 0100 0010 0000 1001 1001 1001 1001 1010
  std::cout << mf.f
            << std::endl; // 0 10000100 00010011001100110011010 = 2^(5) * (1.0 +
                          // (2^(-4) + 2^(-7) + 2(-8) + 2^(-11) + 2^(-12) +
                          // 2^(-15) + 2^-16 + 2^-19 + 2^-20 + 2^-22))
                          // = 2^5 + 2 + 2^(-2) + 2^(-3) + 2^-8 + 2^-9 + 2^-12 +
                          // 2^-13 + 2^-16 + 2^-17 + 2^-19

  std::cout << std::bitset<32>(mf.i)
            << std::endl; // 0100 0010 0000 1001 1001 1001 1001 1010

  std::cout << mf.i << std::endl; // 4 * 16^7 + 2 * 16^6 + 9 * 16^4 + 9 * 16 ^ 3
                                  // + 9 * 16^2 + 9 * 16 + 10
}
